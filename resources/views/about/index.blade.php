                        <h4>Himatika, 25 Tahun yang Lalu</h4>
                        <p>oleh Alm. Dr. Diaraya, M. Ak</p></br>
                        <p>Sulit rasanya memulai menuslis kata demi kata untuk menceritakan kembali kenangan awal berdirinya
                            Himpunan Mahasiswa Matematika FMIPA Unhas 25 Tahun yang lalu. Bukan karena peristiwa 25 tahun
                            yang lalu telah dilupakan, sama sekali bukan. Bahkan teramat sulit untuk melupakannya, karena
                            banyaknya suka dan duka yang telah dilewati di masa yang lalu.</br></br>
                            Kesulitan menulis kata demi kata, mulai terasa sewaktu akan member judul dari tulisan ini.
                            Apalagi untuk merangkai kata-kata dalam bahasa Indonesia yang baik dan benar. Mungkin hal ini
                            disebabkan ketidakbiasaan menulis nostalgia atau cerpen, sehingga terasa kesulitan untuk memulai
                            menulis. Bahkan terasa lebih sulit menulis tentang Himatika di masa lalu, dibanding membuat
                            proposal penelitian atau menulis hibah pengajaran yang baru saja saya selesaikan. Kesulitan
                            menulis surat/cerita yang teratur, juga pernah saya alami sewaktu masih kuliah, betapa sulitnya
                            untuk menulis selembar kertas untuk adik mahasiswa yang dikagumi. Terpaksa pada saat itu,
                            kasak-kusuk mencari beberapa majalah remaja, untuk mengutip kata demi kata yang baik dan sesuai
                            untuk ditulis dalam selembar kertas yang akan dikirim ke mahasiswi tersebut, karena ternyata
                            mahasiswi tersebut berlangganan salah satu majalah yang saya kutip beberapa baris
                            kalimatnya.</br></br>
                            Tulisan ini awal mulana diberi judul Napak Tilas Himatika, namun karena adanya sindiran
                            anak-anak di-Rumah yang berucap: “Wah...Bapak menulis Napak Tilas Jenderal Sudirman waktu
                            bergerilya memperjuangkan Negara Republik Indonesia”. Sambil mengetik di laptop, saya jadi
                            tertawa sendiri mendengar ucapannya yang spontanitas tersebut. Dan akhirnya, ide untuk
                            melanjutkan tulisan dengan judul Napak Tilas Himatika berhenti, karena bersamaan dengan itu, ada
                            keluarga yang datang bertamu.</br></br>
                            Setelah tamu pulang, saya minum obat flu, kemudian melanjutkan lagi mengetik di laptop, walaupun
                            terasa mengantuk karena pengaruh obat dan rasa lelah selama satu minggu ini mengikuti ujian,
                            namun semangat untuk melanjutkan tulisan di malam ini begitu besar, sebab besok pagi ada Tugas
                            SOP (standart Operational Procedure) Jurusan juga harus diselesaikan, begitu pula tugas untuk
                            memeriksa ujian mid test Matematika TPB, Pengolahan Data Citra serta membuat power point materi
                            ajar PIK dan soal ujian Mid test untuk PTS.</br></br>
                            Sebenarnya, keinginan untuk membentuk himpunan mahasiswa di Jurusan Matematika sudah ada
                            semenjak awal diterima menjadi mahasiswa matematika pada tahun 1981, akan tetapi semua itu masih
                            berupa wacana diantara kami angkatan pertama S1 Jurusan Matematika. Angkatan pertama S1
                            Matematika di FMIPA UNHAS, bukan berarti Angkatan pertama di jurusan Matematika FMIPA Unhas.
                            Karena sebelumnya, telah ada, beberapa angkatan mahasiswa di Jurusan Matematika FMIPA Unhas,
                            hanya saja pada saat itu belum berbentuk program S1 akan tetapi berupa program Sarjana Muda yang
                            kemudian melanjutkan studi Sarjana Lengkap di Jawa. Pada saat itu, tidak ada data yang lengkap
                            di Jurusan Matematika tentang nama-nama mahasiswa Jurusan Matematika FMIPA Unhas sebelum
                            angkatan tahun 1981, kecuali nama mahasiswa: Alimin Bado, M. Saleh AF, dan Iwan Marasabessy yang
                            kami ketahui, itupun hanya nama saja tanpa pernah tahu orangnya (maaf, tidak ditulis kata Bapak,
                            karena pada saat itu yang bersangkutan masih berstatus mahasiswa matematika). Kalau istilah
                            gaulnya sekarang, masih ABG, bukan ABC (Atas Bawah Cakar).</br></br>
                            Mahasiswa Jurusan Matematika FMIPA Unhas pada saat itu terasa sebagai manusia langka,
                            seakan-akan kami angkatan 1981 (berjumlah 16 mahasiswa termasuk yang kemudian pindah,tidak aktif
                            dan menikah) adalah mahasiswa matematika pertama di FMIPA Unhas. Kemudian pada tahun 1982,
                            bertambah lagi mahasiswa matematika yang berjumlah 3 (tiga) orang. Jumlah mahasiswa program S1
                            paling langka pada program studi di Unhas sampai sekarang.</br></br>
                            Pada awal April 1983, diadakan rapat pertama untuk membentuk Himpunan Matematika FMIPA Unhas
                            yang diselenggarakan di Jl. Pongtiku (rumahnya Nire, sekarang namanya Pak Nirwan Ilyas). Rapat
                            pertama tersebut kemudian dilanjutkan pada tanggal 11 April 1983 di ruang K.13 (Ruang ini adalah
                            satu-satunya ruang yang digunakan oleh mahasiswa Jurusan Matematika FMIPA Unhas untuk kuliah dan
                            kegiatan lainnya).</br></br>
                            Pada tanggal 11 April ‘83, diruang K.13 inilah pertama kalinya disetujui nama HIMATIKA untuk
                            nama Himpunan Mahasiswa di Jurusan Matematika FMIPA Unhas.</br></br>
                            Georafis ruang K.13, letaknya di tengah-tengah Kampus Unhas Baraya, dan bertetangga langsung
                            dengan Fakultas pertanian. Sekarang ruang k.13 telah menjadi Perumahan Dosen Unhas
                            Baraya.</br></br>
                            Banyak kenangan indah dan manis di ruang K.13, namun juga tidak sedikit dukanya. Di ruang K.13
                            inilah, kami mengenal Analisa Fungsi Rill, Aljabar Abstrak, Statistika Matematika, Teknik
                            Sampling, Didaktuk Matematika, Metode Numerik, Komputasi dan lain sebagainya. Di ruang K.13 ini
                            kami melaksanakan ujian, dimana semua pesertanya dapat nilai E. Pada musim hujan, kuliah di
                            ruang K.13 terkadang berdiri, karena tempat duduknya tergenang air. Begitupula, jalanan menuju
                            ruang K.13 dari arah utara ada selokan besar, pada musim hujan tertutup oleh air, sehingga tidak
                            sedikit mahasiswa yang akan kuliah jatuh ke selokan tersebut. Celana dan bajunya basah. Diruang
                            K.13 pula kami merasakan Seminar Proposal Skripsi berkali-kali (bahkan ada yang sampai tujuh
                            kali Seminar Proposal Skripsi). Yang membuat kami sedih, bukan hanya berkali-kali seminar
                            proposal, tetapi juga biaya konsumsi dan fotokopy materi seminar untuk semu peserta yang hadir
                            (mahasiswa dan dosen) yang membuuat kami sedih. Begitupula perkuliahan di ruang K.13, terkadang
                            membuat kami kuliah merasa jenuh, karena dosennya itu-itu terus yang berjumlah 5 orang (kasihan
                            staf dosen tetap pada saat itu, beban tugasnya teramat berat karena mengajar berbagai matakuliah
                            tanpa dosen pendamping, belum lagi tugasnya mengajar TPB Unhas sebanyak 40 kelas. Semoga amal
                            jariyah mereka dilipatgandakan oleh Allah Swt.</br></br>
                            Adapun sukanya, di ruang K. 13 kami menyelesaikan Ujian Seminar Proposal dan Seminar Hasil, itu
                            artinya sebentar lagi sarjana...sebentar lagi bekerja… sebentar lagi mendapatkan gaji,
                            buntutnya… sebentar lagi menikah.</br></br>
                            Meskipun hanya memiliki satu ruangan untuk kuliah dan kegiatan himpunan, bukan berarti Himatika
                            tidak mempunyai kegiatan. Himatika membuat Diktat Matematika beserta modul-modul matematika
                            setelah sebelumnya minta izin pada Ketua Jurusan dan beberapa Dosen Matematika. Jelas, dana awal
                            harus ditalangi dulu, karena tidak ada bantuan dana dari Jurusan, Fakultas maupun Universitas.
                            Keuntungannya digunakan untuk kegiatan Himatika. Pada saat itu, melaksanakan Bina Akrab di
                            Malino (dekat Kanreapia) dengan menyewa dua mobil (Bus Unhas). Semua mahasiswa lama dan dosen
                            (ternasuk keluarga)tidak di pungut biaya, mahasiswa baru hanya dipungut biaya konsumsi saja.
                            Disamping itu, Himatika mendanai pembenahan ruang baru serta membeli mesin ketik dan peralatan
                            lainnya untuk kegiatan organisasi, termasuk penyediaan ruang untuk sholat dan perlengkapannya.
                            Dan pada akhir masa jabatan sebagai pengurus Himatika, dibentuk Musyawarah kerja dan Panitia
                            Independen dari wakil Angkatan Mahasiswa Matematika untuk memeriksa pertanggungjawaban
                            Kepengurusan Himatika yang akan berakhir, serta ditembuskan kepada Ketua Jurusan Matematika
                            sebagai laporan.</br></br>
                            Tak terasa malam sudah semakin larut, jarum jam hampir menunjukkan pukul 4 dinihari, lagipula
                            saya belum sholat lail dan witir, dan itu berarti sudah lima jam saya menulis kenangan tentang
                            Himmatika. Terus terang Sampai pagipun saya masih sanggup melanjtukan tulisan ini, meskipun rasa
                            kantuk semakin menjadi-jadi. Tapi saya sangsi, nanti adik-adik mahasiswa di Himatika bosan
                            membaca tulisan ini. Karena mungkinn judulnya tidak sesuai dengan iisi. Yang jelas saya telah
                            menulis apa adanya tentang awal terbentuknya Himatika dan kenangan masa lalu di Himatika, sesuai
                            permintaan panitia untuk salah satu tulisan pada kado Buat adik-adik di Himatika. Semoga
                            adik-adik mahasiswa di Himatika memaklumi tulisan ini, anggap saja tulisan ini adalah surat
                            seorang kakak yang menceritakan pengalaman dimasa lalu untuk adik-adiknya di Himatika.</br></br>
                            Dalam menulis ini, saya merasakan masa 23 tahun yang lalu seakan-akan baru kemarin terjadi.
                            Kenangan manis dan indah di ruang K.13 menjadi catatan sejarah dalam perjalanan hidup ini. Ruang
                            K.13 adalah tempat bersejarah, karena di ruangan tersebut pertama kalinya nama Himatika
                            disetujui dalam musyawarah. Dan sekarang, Alhamduliilah nama Himatika masih digunakan oleh
                            Himpunan Mahasiswa Matematika. Itu berarti, telah 25 tahun nama tersebut digunakan oleh Himpunan
                            Mahasiswa Matematika FMIPA Unhas.</br></br>
                            Semoga diusis yang telah dewasa ini, Himatika menghasilkan mahasiswa-mahasiswa yang beriman,
                            bertaqwa dan selalu menjunjung nama baik Himpunan Mahasiswa Matematika FMIPA Unhas dimanapun
                            berada, amin.</br></br>
                            By Drs. Diaraya, M.Ak.</br>
                            Dikutip dari judul asli : Himatika 25 Tahun yang lalu</br>
                            Sumber : Buletin Himatika Edisi 1 Maret 2009</p>

